export type DetailCopy = (typeof detailCopy)["cn"];
export const rowLabel = (t: DetailCopy, row: TimelineRowType) => (row === "motion" || row === "call" ? t.rows[row] : t.types[row]);

const pad = (value: number) => String(value).padStart(2, "0");
export const formatDateTime = (time: number) => {
  const date = new Date(time);
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} ${pad(date.getHours())}:${pad(date.getMinutes())}:${pad(date.getSeconds())}`;
};
export const formatClock = (time: number) => {
  const date = new Date(time);
  return `${pad(date.getHours())}:${pad(date.getMinutes())}:${pad(date.getSeconds())}`;
};
